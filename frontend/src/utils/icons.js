export function icon(name, size = 20) {
  const paths = PATHS[name];
  if (!paths) return '';

  return `<svg class="icon" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">${paths}</svg>`;
}

export function initIcons(root = document) {
  root.querySelectorAll('[data-icon]').forEach((element) => {
    const name = element.dataset.icon;
    if (!name || element.querySelector('svg')) return;

    element.innerHTML = icon(name);
    element.setAttribute('aria-hidden', 'true');
  });
}
